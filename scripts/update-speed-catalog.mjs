// Use the same pinned Showdown version as the battle reference.
import { readFile, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
const root = new URL('../', import.meta.url);
const reference = JSON.parse(await readFile(new URL('public/data/reference.json', root)));
const sourceUrl = `https://raw.githubusercontent.com/smogon/pokemon-showdown/${reference.showdownRevision}/data/mods/champions/formats-data.ts`;
let source;
if (process.argv[2]) source = await readFile(process.argv[2], 'utf8');
else {
  const response = await fetch(sourceUrl);
  if (!response.ok) throw Error(`Catalog unavailable: ${response.status}`);
  source = await response.text();
}
const { FormatsData } = await import(
  `data:text/javascript;base64,${Buffer.from(stripTypeScriptTypes(source)).toString('base64')}`
);
const ids = Object.entries(FormatsData)
  .filter(
    ([id, record]) => !record.isNonstandard && record.tier !== 'Illegal' && reference.species[id],
  )
  .map(([id]) => id)
  .sort();
if (ids.length < 100) throw Error('Unexpectedly incomplete Champions catalog');
await writeFile(
  new URL('src/speed-catalog.js', root),
  `// Generated by scripts/update-speed-catalog.mjs.\n// Source: ${sourceUrl}\nexport const SPEED_SPECIES = new Set(${JSON.stringify(ids, null, 2)});\n`,
);
console.log(`Speed catalog: ${ids.length} forms`);
