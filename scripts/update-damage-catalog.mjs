// 데미지 계산기가 쓰는 목록을 만든다. 도감(reference.json)과 같은 고정 Showdown 리비전.
//  NFE_SPECIES          아직 진화할 수 있는 폼. 진화의휘석이 이 포켓몬에게만 듣는다.
//  SPREAD_MOVES         더블에서 여럿을 한꺼번에 치는 기술(전체기). 데미지가 0.75배가 된다.
//  SHEER_FORCE_MOVES    부가효과가 있는 기술. 우격다짐이 위력을 1.3배로 올린다.
//  NO_PARENTAL_BOND     부자유친으로 두 번 때리지 않는 기술(모으는 기술과 noparentalbond).
//  BREAKABLE_ABILITIES  틀깨기류가 무시하는 방어 측 특성(flags.breakable).
// 챔피언스 모드는 기술 표를 덮어쓰므로(moves.ts) 대상 범위·부가효과도 덮어쓴 값을 따른다.
import { readFile, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
const root = new URL('../', import.meta.url);
const reference = JSON.parse(await readFile(new URL('public/data/reference.json', root)));
const base = `https://raw.githubusercontent.com/smogon/pokemon-showdown/${reference.showdownRevision}/data`;

async function load(path, name) {
  const response = await fetch(`${base}/${path}`);
  if (!response.ok) throw Error(`${path} unavailable: ${response.status}`);
  const source = stripTypeScriptTypes(await response.text());
  const module = await import(
    `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`
  );
  return module[name];
}

const pokedex = await load('pokedex.ts', 'Pokedex');
const moves = await load('moves.ts', 'Moves');
const championsMoves = await load('mods/champions/moves.ts', 'Moves');
const abilities = await load('abilities.ts', 'Abilities');
const moveData = id => ({ ...moves[id], ...championsMoves[id] });
const attacking = Object.keys(reference.move).filter(
  id => reference.move[id].category !== 'Status' && moves[id],
);

const nfe = Object.keys(reference.species)
  .filter(id => pokedex[id]?.evos?.length)
  .sort();
const SPREAD = new Set(['allAdjacent', 'allAdjacentFoes']);
const spread = attacking.filter(id => SPREAD.has(moveData(id).target)).sort();
const sheerForce = attacking
  .filter(id => moveData(id).secondary || moveData(id).secondaries?.length)
  .sort();
const noParentalBond = attacking
  .filter(id => moveData(id).flags?.noparentalbond || moveData(id).flags?.charge)
  .sort();
const breakable = Object.keys(reference.ability)
  .filter(id => abilities[id]?.flags?.breakable)
  .sort();
if (nfe.length < 50 || spread.length < 20 || sheerForce.length < 100 || breakable.length < 30)
  throw Error('Unexpectedly small catalog');

const set = (comment, name, ids) =>
  `// ${comment}\nexport const ${name} = new Set(${JSON.stringify(ids, null, 2)});\n`;
await writeFile(
  new URL('src/damage-catalog.js', root),
  `// Generated by scripts/update-damage-catalog.mjs.\n// Source: ${base}/{pokedex,moves,abilities,mods/champions/moves}.ts\n` +
    set('아직 진화할 수 있는 폼(진화의휘석)', 'NFE_SPECIES', nfe) +
    set('더블에서 여럿을 치는 기술(전체기, 데미지 0.75배)', 'SPREAD_MOVES', spread) +
    set('부가효과가 있는 기술(우격다짐 1.3배)', 'SHEER_FORCE_MOVES', sheerForce) +
    set('부자유친으로 두 번 때리지 않는 기술', 'NO_PARENTAL_BOND', noParentalBond) +
    set('틀깨기류가 무시하는 특성', 'BREAKABLE_ABILITIES', breakable),
);
console.log(
  `Damage catalog: ${nfe.length} NFE, ${spread.length} spread, ${sheerForce.length} sheer force, ` +
    `${noParentalBond.length} no parental bond, ${breakable.length} breakable`,
);
